"""Round 1: reference baselines and default models, compared on VALIDATION only (test locked).

Writes reports/round1/ (git), experiments/r1-*/ (git), data/processed/predictions/r1/ (DVC) and
docs/model_round1.md. Mirrors each run to MLflow (non-fatal).

Run: .venv/bin/python pipelines/04_round1.py [--dry-run] [--no-sync]
"""

import pandas as pd
from sklearn.metrics import precision_recall_curve

from frostwatch_ml import cli, config, runner
from frostwatch_ml.dataio.tables import write_csv, write_json, write_text
from frostwatch_ml.evaluation import plots, reports
from frostwatch_ml.evaluation.cells import MAIN, skill
from frostwatch_ml.evaluation.metrics import METRIC_EXPLANATIONS
from frostwatch_ml.models.registry import build
from frostwatch_ml.tracking import mlflow_logger

OUT = config.REPORTS / "round1"


def main() -> None:
    args = cli.parser(__doc__, "configs/model.yaml").parse_args()
    mcfg = config.load_yaml(args.config)
    data = runner.load_model_data()
    plan = mcfg["round1"]["baselines"] + [m["name"] for m in mcfg["round1"]["models"]]
    print(f"train {len(data.train)} rows, validation {len(data.val)} rows, {len(data.features)} features; models: {plan}")
    if args.dry_run:
        return

    results, runs = [], []
    specs = [(b, b, {"doy_halfwidth": mcfg["round1"]["climatology_doy_halfwidth"]} if b == "climatology" else {})
             for b in mcfg["round1"]["baselines"]]
    specs += [(m["name"], m["kind"], m["params"]) for m in mcfg["round1"]["models"]]
    for name, kind, params in specs:
        model = build(kind, data.features, seed=args.seed, name=name, **params)
        res = runner.evaluate(model, data, name=name)
        results.append(res)
        runs.append(runner.record(res, data, "r1", kind, params, args.seed))
        print(f"{name:15s} PR-AUC {res.pooled['pr_auc']:.4f}  F2 {res.pooled['f2']:.4f}  macro PR-AUC {res.macro['pr_auc']:.4f}")

    pooled = pd.DataFrame({r.name: r.pooled for r in results}).T[MAIN + ["threshold", "base_rate"]]
    pooled.index.name = "model"
    macro_t = pd.DataFrame({r.name: r.macro for r in results}).T[MAIN + ["base_rate"]]
    macro_t.index.name = "model"
    cells = pd.concat([r.cells.assign(model=r.name) for r in results]).reset_index()
    sk_pooled = skill(pooled)
    sk_macro = skill(macro_t)
    reports.save_table(pooled, OUT / "comparison_pooled", title="Round 1, validation, pooled over the 8 cells")
    reports.save_table(macro_t, OUT / "comparison_macro", title="Round 1, validation, macro-average over the 8 cells")
    reports.save_table(sk_pooled, OUT / "skill_vs_baselines", title="Round 1, validation, skill vs best baseline (pooled)")
    reports.save_table(sk_macro, OUT / "skill_vs_baselines_macro", title="Round 1, validation, skill vs best baseline (macro)")
    write_csv(cells, OUT / "per_cell_metrics.csv", index=False)
    write_json({r.name: r.threshold for r in results}, OUT / "thresholds.json")
    write_json(runs, OUT / "runs.json")

    y = data.val["frost"].to_numpy(int)
    curves = {}
    for r in results:
        if r.name in ("majority",):
            continue
        p, rc, _ = precision_recall_curve(y, r.score_val)
        curves[r.name] = pd.DataFrame({"precision": p, "recall": rc})
    plots.pr_curves(curves, float(y.mean()), "Precision-recall on validation (2010-2017)", OUT / "figures" / "pr_curves_validation.png")
    write_doc(pooled, macro_t, sk_pooled, sk_macro, cells, data)
    status = mlflow_logger.status()
    print("mlflow:", "ok" if status["enabled"] else f"disabled ({status['reason']})")
    cli.finish("04_round1", args)


def write_doc(pooled, macro_t, sk_pooled, sk_macro, cells, data) -> None:
    pr_cells = cells.pivot_table(index="point_id", columns="model", values="pr_auc")
    f2_cells = cells.pivot_table(index="point_id", columns="model", values="f2")
    base = cells.groupby("point_id")["base_rate"].first().to_frame("validation_base_rate")
    lines = [
        "# Round 1: baselines and default models (validation only)",
        "",
        "Generated by `pipelines/04_round1.py`. Train 1985-2009, validation 2010-2017; the test set (2018-2025) is locked and was not used. "
        "Every model is fitted on training rows; each decision threshold maximizes F2 on validation. Labels come from the same ERA5-Land reanalysis as the features (grid frost, not station frost).",
        "",
        "Frost nights trend down over 1985-2025: the validation base rate is lower than in training, and the test base rate is lower still. Base rates also differ a lot between cells, so results are given pooled, per cell and as the macro-average over the 8 cells.",
        "",
        "## Metrics in one sentence",
        *[f"- **{k}**: {v}" for k, v in METRIC_EXPLANATIONS.items()],
        "",
        "Decision metrics: PR-AUC and F2. The dew point rule is a score, not a probability, so its Brier score is not defined. Persistence is a 0/1 forecast; its Brier score equals its error rate.",
        "",
        "## Pooled (all validation nights)",
        reports.md_table(pooled, 4),
        "",
        "## Macro-average over the 8 cells",
        reports.md_table(macro_t, 4),
        "",
        "## Skill against the best baseline",
        "Difference in PR-AUC and F2 against the better of climatology and persistence, and Brier skill score against climatology (1 - Brier / Brier_climatology).",
        "",
        "Pooled:",
        "",
        reports.md_table(sk_pooled, 4),
        "",
        "Macro:",
        "",
        reports.md_table(sk_macro, 4),
        "",
        "## Per cell: validation base rate, PR-AUC and F2",
        reports.md_table(base, 3),
        "",
        reports.md_table(pr_cells, 3),
        "",
        reports.md_table(f2_cells, 3),
        "",
        "![PR curves](../reports/round1/figures/pr_curves_validation.png)",
        "",
        "No confidence intervals are computed; small differences may be noise.",
        "",
    ]
    write_text("\n".join(lines), config.DOCS / "model_round1.md")


if __name__ == "__main__":
    main()
