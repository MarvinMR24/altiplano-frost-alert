"""Download point time series from the Copernicus CDS, one request at a time.

Datasets are described in configs/cds_datasets.yaml. A dataset selects its point either
with an area box (selection: area) or with a single location (selection: location), and
returns hourly or daily values (time_step).

Modes:
  --test NAME  one test request from the dataset config, then print a description of the file and stop.
  --run   every point and every date range in the dataset config, in priority order.

Rules: a single process (lock file), no threads, no automatic retries, 10 s between
requests. On any error the script records it in the manifest and exits. Re-running
skips files already marked complete. The API key is read from .env and never logged.
"""

import argparse
import datetime as dt
import hashlib
import json
import logging
import os
import sys
import time
import zipfile
from pathlib import Path

import cdsapi
import numpy as np
import xarray as xr
import yaml
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
CDS_DIR = ROOT / "data" / "raw" / "cds"
LOCK_PATH = CDS_DIR / ".lock"
MANIFEST_PATH = CDS_DIR / "manifest.json"
LOG_PATH = ROOT / "logs" / "cds_download.log"
DEFAULT_URL = "https://cds.climate.copernicus.eu/api"
PAUSE_SECONDS = 10
CELL_TOL = 1e-6
STEP_SECONDS = {"hourly": 3600, "daily": 86400}

log = logging.getLogger("cds_download")


def setup_logging():
    LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    fmt = logging.Formatter("%(asctime)s %(levelname)s %(message)s")
    file_handler = logging.FileHandler(LOG_PATH)
    file_handler.setFormatter(fmt)
    stream_handler = logging.StreamHandler(sys.stdout)
    stream_handler.setFormatter(fmt)
    log.setLevel(logging.INFO)
    log.addHandler(file_handler)
    log.addHandler(stream_handler)


def acquire_lock():
    CDS_DIR.mkdir(parents=True, exist_ok=True)
    try:
        fd = os.open(LOCK_PATH, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError:
        print(f"Lock file {LOCK_PATH} exists: another download may be running. "
              "If no other process is running, delete the lock file by hand.")
        sys.exit(2)
    with os.fdopen(fd, "w") as f:
        f.write(f"pid={os.getpid()} started={dt.datetime.now(dt.timezone.utc).isoformat()}\n")


def release_lock():
    LOCK_PATH.unlink(missing_ok=True)


def load_manifest():
    if MANIFEST_PATH.exists():
        return json.loads(MANIFEST_PATH.read_text())
    return {"files": {}}


def save_manifest(manifest):
    tmp = MANIFEST_PATH.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(manifest, indent=2))
    tmp.replace(MANIFEST_PATH)


def make_client():
    load_dotenv(ROOT / ".env")
    key = os.environ.get("CDS_API_KEY")
    if not key:
        print("CDS_API_KEY is missing from .env")
        sys.exit(2)
    url = os.environ.get("CDS_API_URL", DEFAULT_URL)
    # retry_max=1: the client must not retry failed calls on its own.
    return cdsapi.Client(url=url, key=key, retry_max=1, quiet=False, progress=False)


def check_node_se(point):
    """The configured box must be [lat0 + 0.1, lon0 - 0.1, lat0, lon0] for the expected cell."""
    lat0, lon0 = point["cell"]
    expected = [lat0 + 0.1, lon0 - 0.1, lat0, lon0]
    if any(abs(a - b) > CELL_TOL for a, b in zip(point["area"], expected)):
        print(f"{point['id']}: area {point['area']} does not match node_se box {[round(v, 6) for v in expected]}")
        sys.exit(2)


def build_request(ds_cfg, date, point):
    # Key names and order follow the request generated by each dataset's form.
    if ds_cfg.get("selection", "area") == "location":
        return {
            "variable": list(ds_cfg["variables"]),
            "location": {"longitude": point["lon"], "latitude": point["lat"]},
            "date": [date],
            "data_format": ds_cfg["data_format"],
        }
    return {
        "variable": list(ds_cfg["variables"]),
        "date": [date],
        "data_format": ds_cfg["data_format"],
        "area": list(point["area"]),
    }


def selection_label(ds_cfg, point):
    if ds_cfg.get("selection", "area") == "location":
        return f"location=({point['lat']}, {point['lon']})"
    return f"area={point['area']}"


def cell_check(ds_cfg, point, grid_points):
    """exact: one cell equal to point['cell']. Otherwise one cell within max_offset_deg of (lat, lon)."""
    if len(grid_points) != 1:
        return False
    lat, lon = grid_points[0]
    max_offset = ds_cfg.get("max_offset_deg")
    if max_offset is None:
        exp_lat, exp_lon = point["cell"]
        return abs(lat - exp_lat) < CELL_TOL and abs(lon - exp_lon) < CELL_TOL
    return abs(lat - point["lat"]) <= max_offset and abs(lon - point["lon"]) <= max_offset


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def netcdf_paths(path):
    """Return the NetCDF files behind a download (the file itself, or the members of a zip)."""
    if not zipfile.is_zipfile(path):
        return [path], False
    out_dir = path.with_name(path.stem + "_unzipped")
    out_dir.mkdir(exist_ok=True)
    with zipfile.ZipFile(path) as zf:
        zf.extractall(out_dir)
    return sorted(out_dir.rglob("*.nc")), True


def time_name(ds):
    for name in ("valid_time", "time", "date"):
        if name in ds.coords or name in ds.dims:
            return name
    return None


def coord_values(ds, names):
    for name in names:
        if name in ds.coords or name in ds.variables:
            return np.atleast_1d(ds[name].values).astype(float)
    return np.array([])


def inspect_file(path, point, ds_cfg):
    """Open the download with xarray and collect the checks recorded in the manifest."""
    nc_files, was_zip = netcdf_paths(path)
    parts = [xr.open_dataset(p) for p in nc_files]
    ds = xr.merge(parts, compat="override", join="outer") if len(parts) > 1 else parts[0]
    try:
        tname = time_name(ds)
        times = ds[tname].values if tname else np.array([])
        lats = coord_values(ds, ("latitude", "lat"))
        lons = coord_values(ds, ("longitude", "lon"))
        grid_points = sorted({(float(a), float(b)) for a in lats for b in lons}) if lats.size and lons.size else []
        cell_ok = cell_check(ds_cfg, point, grid_points)
        step = STEP_SECONDS[ds_cfg.get("time_step", "hourly")]

        steps = np.diff(times).astype("timedelta64[s]").astype(int) if times.size > 1 else np.array([])
        step_counts = {int(s): int(c) for s, c in zip(*np.unique(steps, return_counts=True))}
        gaps = int((steps > step).sum()) if steps.size else 0

        data_vars = list(ds.data_vars)
        return {
            "was_zip": was_zip,
            "netcdf_files": [str(p.relative_to(ROOT)) for p in nc_files],
            "data_vars": data_vars,
            "dims": {k: int(v) for k, v in ds.sizes.items()},
            "units": {v: ds[v].attrs.get("units", "") for v in data_vars},
            "long_names": {v: ds[v].attrs.get("long_name", "") for v in data_vars},
            "time_coord": tname,
            "n_timestamps": int(times.size),
            "time_start": str(times.min()) if times.size else None,
            "time_end": str(times.max()) if times.size else None,
            "step_seconds_counts": step_counts,
            "gaps_over_step": gaps,
            "nan_counts": {v: int(ds[v].isnull().sum().item()) for v in data_vars},
            "grid_points_returned": grid_points,
            "expected_cell": point.get("cell") if ds_cfg.get("max_offset_deg") is None else None,
            "max_offset_deg": ds_cfg.get("max_offset_deg"),
            "cell_assertion_ok": cell_ok,
            "t2m_le_0C_hours": int((ds["t2m"] <= 273.15).sum().item()) if "t2m" in ds else None,
        }
    finally:
        for p in parts:
            p.close()


def download_one(client, manifest, ds_name, ds_cfg, point, date, out_path, use):
    key = str(out_path.relative_to(ROOT))
    entry = manifest["files"].get(key)
    if entry and entry.get("status") == "complete":
        log.info("skip %s (complete in manifest)", key)
        return False

    # A file that downloaded fine but failed inspection is checked again without a new request.
    if entry and entry.get("sha256") and out_path.exists() and sha256_of(out_path) == entry["sha256"]:
        log.info("reuse downloaded %s (sha256 matches), inspecting only", key)
        return inspect_and_finish(manifest, entry, key, out_path, point, ds_cfg)

    request = build_request(ds_cfg, date, point)
    record = {
        "point_id": point["id"],
        "target_lat": point["lat"],
        "target_lon": point["lon"],
        "selection": ds_cfg.get("selection", "area"),
        "area": point["area"] if ds_cfg.get("selection", "area") == "area" else None,
        "expected_cell": point["cell"] if ds_cfg.get("max_offset_deg") is None else None,
        "dataset_name": ds_name,
        "dataset_id": ds_cfg["dataset_id"],
        "request_dates": date,
        "use": use,
        "started_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "status": "started",
    }
    manifest["files"][key] = record
    save_manifest(manifest)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    log.info("request %s %s date=%s %s -> %s", ds_cfg["dataset_id"], point["id"], date, selection_label(ds_cfg, point), key)
    t0 = time.time()
    try:
        client.retrieve(ds_cfg["dataset_id"], request, str(out_path))
    except Exception as exc:  # any CDS error stops the run, no retry
        record.update(status="error", error=f"{type(exc).__name__}: {exc}",
                      finished_at=dt.datetime.now(dt.timezone.utc).isoformat())
        save_manifest(manifest)
        log.error("request failed for %s: %s: %s", key, type(exc).__name__, exc)
        raise SystemExit(1)

    record["download_seconds"] = round(time.time() - t0, 1)
    record["file_size_bytes"] = out_path.stat().st_size
    record["sha256"] = sha256_of(out_path)
    save_manifest(manifest)
    return inspect_and_finish(manifest, record, key, out_path, point, ds_cfg)


def time_failures(info, date_range, time_step):
    """Hourly: UTC series from start 00:00 to end 23:00. Daily: one value per date from start to end.
    Both with a constant step and no gaps."""
    start, end = date_range.split("/")
    if time_step == "daily":
        first, last, unit = np.datetime64(start, "D"), np.datetime64(end, "D"), "D"
    else:
        first, last, unit = np.datetime64(f"{start}T00:00"), np.datetime64(f"{end}T23:00"), "m"
    expected_n = int((last - first) / np.timedelta64(1, "h" if time_step == "hourly" else "D")) + 1
    out = []
    if info["time_start"] is None or np.datetime64(info["time_start"], unit) != first:
        out.append(f"time start {info['time_start']} != {first}")
    if info["time_end"] is None or np.datetime64(info["time_end"], unit) != last:
        out.append(f"time end {info['time_end']} != {last}")
    if info["n_timestamps"] != expected_n:
        out.append(f"time count {info['n_timestamps']} != {expected_n}")
    if set(info["step_seconds_counts"]) != {STEP_SECONDS[time_step]} or info["gaps_over_step"]:
        out.append(f"time step not {time_step}: {info['step_seconds_counts']}")
    info["expected_timestamps"] = expected_n
    return out


def inspect_and_finish(manifest, record, key, out_path, point, ds_cfg):
    record.pop("error", None)
    try:
        info = inspect_file(out_path, point, ds_cfg)
    except Exception as exc:
        record.update(status="error", error=f"inspect failed: {type(exc).__name__}: {exc}",
                      finished_at=dt.datetime.now(dt.timezone.utc).isoformat())
        save_manifest(manifest)
        log.error("could not open %s: %s: %s", key, type(exc).__name__, exc)
        raise SystemExit(1)

    record["checks"] = info
    record["finished_at"] = dt.datetime.now(dt.timezone.utc).isoformat()
    failures = []
    if not info["cell_assertion_ok"]:
        target = info["expected_cell"] or f"within {info['max_offset_deg']} deg of ({point['lat']}, {point['lon']})"
        failures.append(f"cell assertion failed: expected one cell {target}, got {info['grid_points_returned']}")
    failures += time_failures(info, record["request_dates"], ds_cfg.get("time_step", "hourly"))
    info["time_assertion_ok"] = not any(f.startswith("time") for f in failures)
    if failures:
        record.update(status="error", error="; ".join(failures))
        save_manifest(manifest)
        log.error("%s: %s", key, record["error"])
        print_test_report(record)
        raise SystemExit(1)
    record["grid_lat"], record["grid_lon"] = info["grid_points_returned"][0]
    record["status"] = "complete"
    save_manifest(manifest)
    log.info("done %s size=%d bytes timestamps=%d gaps=%d cell=%s",
             key, record["file_size_bytes"], info["n_timestamps"], info["gaps_over_step"], info["grid_points_returned"][0])
    return True


def print_test_report(record):
    c = record["checks"]
    print("\n=== TEST FILE REPORT ===")
    print(f"file size: {record['file_size_bytes']} bytes, sha256 {record['sha256'][:16]}...")
    print(f"zip archive: {c['was_zip']}  netcdf files: {c['netcdf_files']}")
    print(f"dimensions: {c['dims']}")
    print(f"time coord: {c['time_coord']}  timestamps: {c['n_timestamps']} (expected {c.get('expected_timestamps')})")
    print(f"time range: {c['time_start']} -> {c['time_end']}")
    print(f"time step counts (seconds: count): {c['step_seconds_counts']}  gaps: {c['gaps_over_step']}")
    print(f"requested: ({record['target_lat']}, {record['target_lon']})  grid points returned: {c['grid_points_returned']}")
    rule = f"expected cell {c['expected_cell']}" if c["expected_cell"] else f"max offset {c['max_offset_deg']} deg"
    print(f"number of cells: {len(c['grid_points_returned'])}  {rule}  "
          f"assertion: {'PASS' if c['cell_assertion_ok'] else 'FAIL'}")
    if c["t2m_le_0C_hours"] is not None:
        print(f"hours with t2m <= 0 C: {c['t2m_le_0C_hours']}")
    print(f"total NaN: {sum(c['nan_counts'].values())}")
    print("variables (units, long name, NaN count):")
    for v in c["data_vars"]:
        print(f"  {v:10s} {c['units'][v]:12s} {c['long_names'][v]:45s} NaN={c['nan_counts'][v]}")


def print_summary(manifest):
    print("\n=== SUMMARY ===")
    print(f"{'file':55s} {'status':9s} {'MB':>8s} {'steps':>7s} {'gaps':>5s} grid")
    for key, r in manifest["files"].items():
        c = r.get("checks", {})
        size = r.get("file_size_bytes")
        print(f"{key:55s} {r['status']:9s} {size / 1e6 if size else 0:8.1f} "
              f"{c.get('n_timestamps', 0):7d} {c.get('gaps_over_step', c.get('gaps_over_1h', 0)):5d} {c.get('grid_points_returned')}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--test", metavar="NAME", help="name of a test under the dataset's tests key")
    mode.add_argument("--run", action="store_true")
    parser.add_argument("--config", default="configs/points.yaml")
    parser.add_argument("--datasets", default="configs/cds_datasets.yaml")
    parser.add_argument("--dataset", default="era5land_ts")
    parser.add_argument("--ranges", nargs="+", help="names of date ranges to download (default: all)")
    args = parser.parse_args()

    points_cfg = yaml.safe_load((ROOT / args.config).read_text())
    points = points_cfg["points"]
    if points_cfg.get("area_mode") == "node_se":
        for p in points:
            check_node_se(p)
    ds_cfg = yaml.safe_load((ROOT / args.datasets).read_text())["datasets"][args.dataset]
    out_dir = ROOT / ds_cfg["out_dir"]

    setup_logging()
    acquire_lock()
    try:
        client = make_client()
        manifest = load_manifest()
        if args.test:
            test = ds_cfg["tests"][args.test]
            point = dict(next(p for p in points if p["id"] == test["point"]))
            point["area"] = test.get("area", point["area"])
            out_path = out_dir / test["file"]
            download_one(client, manifest, args.dataset, ds_cfg, point, test["date"], out_path, f"test_{args.test}")
            print_test_report(manifest["files"][str(out_path.relative_to(ROOT))])
            return

        first = True
        for point in points:
            for rng in ds_cfg["ranges"]:
                if args.ranges and rng["name"] not in args.ranges:
                    continue
                out_path = out_dir / rng["file"].format(id=point["id"])
                key = str(out_path.relative_to(ROOT))
                if manifest["files"].get(key, {}).get("status") == "complete":
                    log.info("skip %s (complete in manifest)", key)
                    continue
                if not first:
                    time.sleep(PAUSE_SECONDS)
                first = False
                download_one(client, manifest, args.dataset, ds_cfg, point, rng["date"], out_path, rng["use"])
        print_summary(manifest)
    finally:
        release_lock()


if __name__ == "__main__":
    main()
