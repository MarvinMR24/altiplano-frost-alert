"""Download ERA5-Land time series from the Copernicus CDS, one request at a time.

Modes:
  --test  El Alto only, July 2025, then print a description of the file and stop.
  --run   every point and every date range in the dataset config, in priority order.

Rules: a single process (lock file), no threads, no automatic retries, 10 s between
requests. On any error the script records it in the manifest and exits. Re-running
skips files already marked complete. The API key is read from .env and never logged.
"""

import argparse
import datetime as dt
import hashlib
import json
import logging
import os
import sys
import time
import zipfile
from pathlib import Path

import cdsapi
import numpy as np
import xarray as xr
import yaml
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parents[1]
CDS_DIR = ROOT / "data" / "raw" / "cds"
LOCK_PATH = CDS_DIR / ".lock"
MANIFEST_PATH = CDS_DIR / "manifest.json"
LOG_PATH = ROOT / "logs" / "cds_download.log"
DEFAULT_URL = "https://cds.climate.copernicus.eu/api"
PAUSE_SECONDS = 10

log = logging.getLogger("cds_download")


def setup_logging():
    LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
    fmt = logging.Formatter("%(asctime)s %(levelname)s %(message)s")
    file_handler = logging.FileHandler(LOG_PATH)
    file_handler.setFormatter(fmt)
    stream_handler = logging.StreamHandler(sys.stdout)
    stream_handler.setFormatter(fmt)
    log.setLevel(logging.INFO)
    log.addHandler(file_handler)
    log.addHandler(stream_handler)


def acquire_lock():
    CDS_DIR.mkdir(parents=True, exist_ok=True)
    try:
        fd = os.open(LOCK_PATH, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError:
        print(f"Lock file {LOCK_PATH} exists: another download may be running. "
              "If no other process is running, delete the lock file by hand.")
        sys.exit(2)
    with os.fdopen(fd, "w") as f:
        f.write(f"pid={os.getpid()} started={dt.datetime.now(dt.timezone.utc).isoformat()}\n")


def release_lock():
    LOCK_PATH.unlink(missing_ok=True)


def load_manifest():
    if MANIFEST_PATH.exists():
        return json.loads(MANIFEST_PATH.read_text())
    return {"files": {}}


def save_manifest(manifest):
    tmp = MANIFEST_PATH.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(manifest, indent=2))
    tmp.replace(MANIFEST_PATH)


def make_client():
    load_dotenv(ROOT / ".env")
    key = os.environ.get("CDS_API_KEY")
    if not key:
        print("CDS_API_KEY is missing from .env")
        sys.exit(2)
    url = os.environ.get("CDS_API_URL", DEFAULT_URL)
    # retry_max=1: the client must not retry failed calls on its own.
    return cdsapi.Client(url=url, key=key, retry_max=1, quiet=False, progress=False)


def build_request(ds_cfg, date, area):
    # Key names and order follow the request generated by the dataset form.
    return {
        "variable": list(ds_cfg["variables"]),
        "date": [date],
        "data_format": ds_cfg["data_format"],
        "area": list(area),
    }


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def netcdf_paths(path):
    """Return the NetCDF files behind a download (the file itself, or the members of a zip)."""
    if not zipfile.is_zipfile(path):
        return [path], False
    out_dir = path.with_name(path.stem + "_unzipped")
    out_dir.mkdir(exist_ok=True)
    with zipfile.ZipFile(path) as zf:
        zf.extractall(out_dir)
    return sorted(out_dir.rglob("*.nc")), True


def time_name(ds):
    for name in ("valid_time", "time", "date"):
        if name in ds.coords or name in ds.dims:
            return name
    return None


def coord_values(ds, names):
    for name in names:
        if name in ds.coords or name in ds.variables:
            return np.atleast_1d(ds[name].values).astype(float)
    return np.array([])


def inspect_file(path, point, expected_vars):
    """Open the download with xarray and collect the checks recorded in the manifest."""
    nc_files, was_zip = netcdf_paths(path)
    parts = [xr.open_dataset(p) for p in nc_files]
    ds = xr.merge(parts, compat="override", join="outer") if len(parts) > 1 else parts[0]
    try:
        tname = time_name(ds)
        times = ds[tname].values if tname else np.array([])
        lats = coord_values(ds, ("latitude", "lat"))
        lons = coord_values(ds, ("longitude", "lon"))
        grid_points = sorted({(float(a), float(b)) for a in lats for b in lons}) if lats.size and lons.size else []
        nearest = None
        if grid_points:
            nearest = min(grid_points, key=lambda p: (p[0] - point["lat"]) ** 2 + (p[1] - point["lon"]) ** 2)

        steps = np.diff(times).astype("timedelta64[s]").astype(int) if times.size > 1 else np.array([])
        step_counts = {int(s): int(c) for s, c in zip(*np.unique(steps, return_counts=True))}
        gaps = int((steps > 3600).sum()) if steps.size else 0

        data_vars = list(ds.data_vars)
        return {
            "was_zip": was_zip,
            "netcdf_files": [str(p.relative_to(ROOT)) for p in nc_files],
            "data_vars": data_vars,
            "dims": {k: int(v) for k, v in ds.sizes.items()},
            "units": {v: ds[v].attrs.get("units", "") for v in data_vars},
            "long_names": {v: ds[v].attrs.get("long_name", "") for v in data_vars},
            "time_coord": tname,
            "n_timestamps": int(times.size),
            "time_start": str(times.min()) if times.size else None,
            "time_end": str(times.max()) if times.size else None,
            "step_seconds_counts": step_counts,
            "gaps_over_1h": gaps,
            "nan_counts": {v: int(ds[v].isnull().sum().item()) for v in data_vars},
            "grid_points_returned": grid_points,
            "grid_nearest": nearest,
            "n_expected_vars": len(expected_vars),
        }
    finally:
        for p in parts:
            p.close()


def download_one(client, manifest, ds_name, ds_cfg, point, date, out_path, use):
    key = str(out_path.relative_to(ROOT))
    entry = manifest["files"].get(key)
    if entry and entry.get("status") == "complete":
        log.info("skip %s (complete in manifest)", key)
        return False

    # A file that downloaded fine but failed inspection is checked again without a new request.
    if entry and entry.get("sha256") and out_path.exists() and sha256_of(out_path) == entry["sha256"]:
        log.info("reuse downloaded %s (sha256 matches), inspecting only", key)
        return inspect_and_finish(manifest, entry, key, out_path, point, ds_cfg)

    request = build_request(ds_cfg, date, point["area"])
    record = {
        "point_id": point["id"],
        "target_lat": point["lat"],
        "target_lon": point["lon"],
        "area": point["area"],
        "dataset_name": ds_name,
        "dataset_id": ds_cfg["dataset_id"],
        "request_dates": date,
        "use": use,
        "started_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "status": "started",
    }
    manifest["files"][key] = record
    save_manifest(manifest)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    log.info("request %s %s date=%s area=%s -> %s", ds_cfg["dataset_id"], point["id"], date, point["area"], key)
    t0 = time.time()
    try:
        client.retrieve(ds_cfg["dataset_id"], request, str(out_path))
    except Exception as exc:  # any CDS error stops the run, no retry
        record.update(status="error", error=f"{type(exc).__name__}: {exc}",
                      finished_at=dt.datetime.now(dt.timezone.utc).isoformat())
        save_manifest(manifest)
        log.error("request failed for %s: %s: %s", key, type(exc).__name__, exc)
        raise SystemExit(1)

    record["download_seconds"] = round(time.time() - t0, 1)
    record["file_size_bytes"] = out_path.stat().st_size
    record["sha256"] = sha256_of(out_path)
    save_manifest(manifest)
    return inspect_and_finish(manifest, record, key, out_path, point, ds_cfg)


def inspect_and_finish(manifest, record, key, out_path, point, ds_cfg):
    record.pop("error", None)
    try:
        info = inspect_file(out_path, point, ds_cfg["variables"])
    except Exception as exc:
        record.update(status="error", error=f"inspect failed: {type(exc).__name__}: {exc}",
                      finished_at=dt.datetime.now(dt.timezone.utc).isoformat())
        save_manifest(manifest)
        log.error("could not open %s: %s: %s", key, type(exc).__name__, exc)
        raise SystemExit(1)

    record["checks"] = info
    record["grid_lat"], record["grid_lon"] = info["grid_nearest"] if info["grid_nearest"] else (None, None)
    record["finished_at"] = dt.datetime.now(dt.timezone.utc).isoformat()
    record["status"] = "complete"
    save_manifest(manifest)
    log.info("done %s size=%d bytes timestamps=%d gaps=%d nearest=%s",
             key, record["file_size_bytes"], info["n_timestamps"], info["gaps_over_1h"], info["grid_nearest"])
    return True


def print_test_report(record):
    c = record["checks"]
    print("\n=== TEST FILE REPORT ===")
    print(f"file size: {record['file_size_bytes']} bytes, sha256 {record['sha256'][:16]}...")
    print(f"zip archive: {c['was_zip']}  netcdf files: {c['netcdf_files']}")
    print(f"dimensions: {c['dims']}")
    print(f"time coord: {c['time_coord']}  timestamps: {c['n_timestamps']} (expected 744)")
    print(f"time range: {c['time_start']} -> {c['time_end']}")
    print(f"time step counts (seconds: count): {c['step_seconds_counts']}  gaps over 1 h: {c['gaps_over_1h']}")
    print(f"grid points returned: {c['grid_points_returned']}")
    print(f"nearest to target ({record['target_lat']}, {record['target_lon']}): {c['grid_nearest']}")
    print("variables (units, long name, NaN count):")
    for v in c["data_vars"]:
        print(f"  {v:10s} {c['units'][v]:12s} {c['long_names'][v]:45s} NaN={c['nan_counts'][v]}")


def print_summary(manifest):
    print("\n=== SUMMARY ===")
    print(f"{'file':55s} {'status':9s} {'MB':>8s} {'hours':>7s} {'gaps':>5s} grid")
    for key, r in manifest["files"].items():
        c = r.get("checks", {})
        size = r.get("file_size_bytes")
        print(f"{key:55s} {r['status']:9s} {size / 1e6 if size else 0:8.1f} "
              f"{c.get('n_timestamps', 0):7d} {c.get('gaps_over_1h', 0):5d} {c.get('grid_nearest')}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--test", action="store_true")
    mode.add_argument("--run", action="store_true")
    parser.add_argument("--config", default="configs/points.yaml")
    parser.add_argument("--datasets", default="configs/cds_datasets.yaml")
    parser.add_argument("--dataset", default="era5land_ts")
    args = parser.parse_args()

    points = yaml.safe_load((ROOT / args.config).read_text())["points"]
    ds_cfg = yaml.safe_load((ROOT / args.datasets).read_text())["datasets"][args.dataset]
    out_dir = ROOT / ds_cfg["out_dir"]

    setup_logging()
    acquire_lock()
    try:
        client = make_client()
        manifest = load_manifest()
        if args.test:
            point = next(p for p in points if p["id"] == ds_cfg["test"]["point"])
            out_path = out_dir / ds_cfg["test"]["file"]
            download_one(client, manifest, args.dataset, ds_cfg, point, ds_cfg["test"]["date"], out_path, "test")
            print_test_report(manifest["files"][str(out_path.relative_to(ROOT))])
            return

        first = True
        for point in points:
            for rng in ds_cfg["ranges"]:
                out_path = out_dir / rng["file"].format(id=point["id"])
                key = str(out_path.relative_to(ROOT))
                if manifest["files"].get(key, {}).get("status") == "complete":
                    log.info("skip %s (complete in manifest)", key)
                    continue
                if not first:
                    time.sleep(PAUSE_SECONDS)
                first = False
                download_one(client, manifest, args.dataset, ds_cfg, point, rng["date"], out_path, rng["use"])
        print_summary(manifest)
    finally:
        release_lock()


if __name__ == "__main__":
    main()
